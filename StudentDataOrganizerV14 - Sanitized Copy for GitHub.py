# Authenticate and connect to Google Sheets
def connect_to_gsheet(credentials_file, sheet_name):
    scope = ["https://spreadsheets.google.com/feeds", "https://www.googleapis.com/auth/spreadsheets", "https://www.googleapis.com/auth/drive.file", "https://www.googleapis.com/auth/drive"]
    creds = ServiceAccountCredentials.from_json_keyfile_name(credentials_file, scope)
    client = gspread.authorize(creds)
    return client.open(sheet_name)

# Function required by the "parse_phone_address_csz()" function that parses address/csz info
# by splitting at the space preceding the rightmost comma and it takes into account the
# special case of a town with a 2-part name
def parse_address_csz(data):
    # rfind searches a string starting from the right side 
    rightmost_comma_index = data.rfind(",")
    space_preceding_comma_index = data.rfind(" ",0,rightmost_comma_index)
    address = data[:space_preceding_comma_index].strip()
    csz = data[space_preceding_comma_index+1:].strip()
    # fixes the special cases of a 2-word city:
    if address[-5:]=="Stony" and csz[:5]=="Point":
        address = address[:-5].strip()
        csz = "Stony " + csz
        csz = csz.strip()
    elif address[-7:]=="Tomkins" and csz[:4]=="Cove":
        address = address[:-7].strip()
        csz = "Tomkins " + csz
        csz = csz.strip()
    elif address[-3:]=="New" and csz[:4]=="City":
        address = address[:-3].strip()
        csz = "New " + csz
        csz = csz.strip()
    elif address[-6:]=="Spring" and csz[:6]=="Valley":
        address = address[:-6].strip()
        csz = "Spring " + csz
        csz = csz.strip()
    return address,csz

# Function required by the "read_and_reorganize_data()" function that parses phone/address info
def parse_phone_address_csz(data):
    data_minus_phone = data[6:]
    # the code splits the string at the word " Address:"
    phone,address_csz = data_minus_phone.split(" Address:")
    address,csz = parse_address_csz(address_csz)
    return phone, address, csz

def parse_guardian_contact_info(data):
    if "Email:" in data:
        # slice the data string and assign only the text that is 6 characters in (following "Email:")
        start_index = data.index("Email:")+6
        email_plus_more = data[start_index:]
        # remove anything that might follow the email address in the string by assigning only
        # the first item in the list generated by the "split" method
        email = email_plus_more.split()[0]
        return email
    else:
        return ""

def sort_my_data(data):
    print("Commencing the sort of the data.")
    headers = data[0]
    actual_data = data[1:]
    # the sort method uses a 'lambda" function as a key specifying the 
    # sort order (0 for Period, 3 for Last Name, and 5 for First Name)
    actual_data.sort(key = lambda x: (x[0], x[3], x[5]))
    sorted_data = [headers] + actual_data
    return sorted_data

def assign_period_identifier(period_string):
    index = period_string.find("(")
    if index == -1:
        print("I saw something unexpected when I tried to determine the student's period.  Program terminated.")
        sys.exit()
    substring = period_string[index+1:]
    if substring.startswith("A, B"):
        # returns only the second character (indexed at 1) of the period_string
        return period_string[1]
    elif substring.startswith("A)"):
        return period_string[1]+"A"
    elif substring.startswith("B)"):
        return period_string[1]+"B"
    else:
        print("I saw something unexpected when I tried to determine the student's period.  Program terminated.")
        sys.exit()

# Function to read/parse data from the source sheet and return a master list
# containing lists of organized data for each student.
def read_and_reorganize_data(sheet):
    # Read all the data in the source sheet by column
    print("Starting to read/organize all student data from the data spreadsheet.")
    all_headers = sheet.row_values(1)
    target_headers = ["Course", "Period", "Last Name", "First Name", "Gender",
    "Grade", "Student Number", "Date of Birth", "Counselor Name", 
    "Phone and Address(1)", "Guardian Contact(1)", "Guardian Contact(2)"]

    # Create a dictionary associating each target header with the number
    # of its column
    print("Finding the columns that contain the desired data.")
    column_indices = {}
    for header in target_headers:
        column_indices[header] = all_headers.index(header)
    # print("The target header column indices are ", column_indices)

    courses_col = column_indices["Course"]+1
    period_col = column_indices["Period"]+1
    last_names_col = column_indices["Last Name"]+1
    first_names_col = column_indices["First Name"]+1
    genders_col = column_indices["Gender"]+1
    grades_col = column_indices["Grade"]+1
    student_ids_col = column_indices["Student Number"]+1
    dobs_col = column_indices["Date of Birth"]+1
    counselors_col = column_indices["Counselor Name"]+1
    phones_addresses_cszs_col = column_indices["Phone and Address(1)"]+1
    parent_email_1s_col = column_indices["Guardian Contact(1)"]+1
    parent_email_2s_col = column_indices["Guardian Contact(2)"]+1

    # print("column indices again: ",courses_col,period_col,last_names_col,first_names_col,genders_col,grades_col,student_ids_col,dobs_col,counselors_col,phones_addresses_cszs_col)

    # Assign the desired columns of data to separate lists
    print("Creating lists to hold the columns of data.")
    courses = sheet.col_values(courses_col)
    periods = sheet.col_values(period_col)
    last_names = sheet.col_values(last_names_col)
    first_names = sheet.col_values(first_names_col)
    genders = sheet.col_values(genders_col)
    grades = sheet.col_values(grades_col)
    student_ids = sheet.col_values(student_ids_col)
    dobs = sheet.col_values(dobs_col)
    counselors = sheet.col_values(counselors_col)
    phones_addresses_cszs = sheet.col_values(phones_addresses_cszs_col)
    parent_email_1s = sheet.col_values(parent_email_1s_col)
    parent_email_2s = sheet.col_values(parent_email_2s_col)
   
    num_students = len(courses)-1
    print("The number of students is ", num_students)

    # Initialize "student_records" list to store the lists of student data
    print("Initializing a master list to contain a list of data for each student.")
    student_records = []
    headers = ["Period", "Course", "Count", "Last Name", "First Name Preferred", "First Name (IC)",
                "Grade Level", "Gender", "ID #", "Birthday", "Counselor", "IC Phone", "Street", 
                "City/State/Zip", "Resource Teacher", "Modifications", "Student Personal Phone", 
                "NRHS Email", "Best Student Email", "Parent Email #1", "Parent Email #2", 
                "GF Parent Phone", "Cum Abs Q1", "Cum Abs Q2", "Cum Abs Q3", "Merged Name"]
    student_records.append(headers)

    # Parse data by taking one piece of data from each column, make that into an individual
    # student data list and then make a master list containing all data for all students
    print("Now creating a list of data for each student and appending each list to the master list of student_records.")
    i = 1
    previous_students_course = "fake course name"
    while i <= num_students:
        course = courses[i]
        # assigns only the second character (indexed at 1) of the "periods" string to period but
        # an "A" or "B" will be included if the student does not appear every day.
        period = assign_period_identifier(periods[i])

        # This block of code enumerates the students in each class
        if course == previous_students_course:
            count_students_in_period += 1
        else:
            count_students_in_period = 1
        previous_students_course = course

        last_name = last_names[i]
        first_name = first_names[i]
        grade = grades[i]
        gender = genders[i]
        student_id = student_ids[i]
        dob = dobs[i]
        counselor = counselors[i]
        phone,address,csz = parse_phone_address_csz(phones_addresses_cszs[i])
        parent_email_1 = parse_guardian_contact_info(parent_email_1s[i])
        try:
            parent_email_2 = parse_guardian_contact_info(parent_email_2s[i])
        except IndexError:
            parent_email_2 = ""
        full_name = first_name + " " + last_name

        # Appending a list of data for a student to the master list of lists of student data.
        # The empty strings are leaving space for data that is to be collected at a later time.
        student_records.append([period,course, count_students_in_period, last_name, "",first_name, grade,
                                 gender, student_id, dob, counselor, phone, address, csz,
                                 "","","","","",parent_email_1,parent_email_2,"","","","",full_name])
        
        i += 1
    student_records = sort_my_data(student_records)
    print("Master list of student data lists has now been created.")
    return student_records

# MAIN FUNCTION TO CONTROL THE DATA TRANSFER
def transfer_data(credentials_file, source_sheet_name, destination_sheet_name):
    # Connect to Google Sheets
    source_sheet = connect_to_gsheet(credentials_file, source_sheet_name).sheet1
    destination_sheet = connect_to_gsheet(credentials_file, destination_sheet_name).sheet1
    
    # Read and reorganize data
    print("Calling the 'read_and_reorganize_data' function.")
    student_data_rows = read_and_reorganize_data(source_sheet)
    
    # Write data to destination sheet
    destination_sheet.update(values = student_data_rows,range_name = "A1")
    print("Data transferred to organized student data spreadsheet successfully, but student emails have yet to be added to this spreadsheet.")


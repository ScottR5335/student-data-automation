# This function pulls email addresses (both student and parent) from the Student Data database.
# It creates a CSV file with 3 columns:  "First Name", "Last Name", and "Email".  The first names
# are like "John1" and the last names are like "P1SDoe".
def create_spreadsheet_for_csv(credentials_file, source_sheet_name, destination_sheet_name):
    # Connect to Google Sheets
    source_sheet = connect_to_gsheet(credentials_file, source_sheet_name).sheet1
    destination_sheet = connect_to_gsheet(credentials_file, destination_sheet_name).sheet1

    # Read all the data in the source sheet by column
    all_headers = source_sheet.row_values(1)

    target_headers = ["Period", "Last Name", "First Name (IC)", "Best Student Email",
        "Parent Email #1", "Parent Email #2"]

    # Create a dictionary associating each target header with the number of its column.
    # The target header column_indices_less_one variable contains the positions of the target headers in the list of target headers.
    column_indices_less_one = {}
    for header in target_headers:
        column_indices_less_one[header] = all_headers.index(header)

    period_col = column_indices_less_one["Period"]+1
    last_names_col = column_indices_less_one["Last Name"]+1
    first_names_col = column_indices_less_one["First Name (IC)"]+1
    student_email_col = column_indices_less_one["Best Student Email"]+1
    parent_email_1_col = column_indices_less_one["Parent Email #1"]+1
    parent_email_2_col = column_indices_less_one["Parent Email #2"]+1

    # Assign the desired columns of data to separate lists
    periods = source_sheet.col_values(period_col)
    last_names = source_sheet.col_values(last_names_col)
    first_names = source_sheet.col_values(first_names_col)
    student_emails = source_sheet.col_values(student_email_col)
    parent_emails_1 = source_sheet.col_values(parent_email_1_col)
    parent_emails_2 = source_sheet.col_values(parent_email_2_col)

    num_students = len(periods)-1
    print("The number of students is ", num_students)

    # Initialize the list to store organized email info
    email_records = []
    headers = ["First Name", "Last Name", "Email"]
    email_records.append(headers)

    # Loop through the 3 email data columns.  If the email isn't empty, then create a first name, create a last name,
    # and append the first name, last name, and email into email records.

    # Loop 1: for student emails data column
    for index in range (1,len(student_emails)):
        email_for_csv = student_emails[index]
        if email_for_csv == "":
            continue
        else:
            first_name_for_csv = first_names[index]+"1"
            last_name_for_csv = "P"+periods[index]+"S"+last_names[index]
            email_records.append([first_name_for_csv,last_name_for_csv,email_for_csv])

    # Loop 2:  for first set of parent emails
    for index in range (1,len(parent_emails_1)):
        email_for_csv = parent_emails_1[index]
        if email_for_csv == "":
            continue
        else:
            first_name_for_csv = first_names[index]+"1"
            last_name_for_csv = "P"+periods[index]+"P"+last_names[index]
            email_records.append([first_name_for_csv,last_name_for_csv,email_for_csv])

    # Loop 3: for second set of parent emails
    for index in range (1,len(parent_emails_2)):
        email_for_csv = parent_emails_2[index]
        if email_for_csv == "":
            continue
        else:
            first_name_for_csv = first_names[index]+"2"
            last_name_for_csv = "P"+periods[index]+"P"+last_names[index]
            email_records.append([first_name_for_csv,last_name_for_csv,email_for_csv])

    destination_sheet.update(range_name = "A1",values = email_records)



